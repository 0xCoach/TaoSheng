"""模拟中断评测；输出实际模型分数及0.5秒响度，由Night203Test调用生产Kotlin规则计数。"""
import csv,json,sys,hashlib,urllib.request
from pathlib import Path
import numpy as np
import sherpa_onnx
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'night202'))
import reference_evaluate as r
r.ROOT=Path('/tmp/taosheng-202-night-eval'); OUT=Path('docs/任务卡/203-证据')
m=list(csv.DictReader((Path.home()/'Developer/TaoSheng-research/snore-eval/results/manifest.csv').open()))
speech=next(v for v in m if v['category']=='speech')
p=r.ROOT/speech['path'];p.parent.mkdir(parents=True,exist_ok=True)
if not p.exists():
    rows=json.load(urllib.request.urlopen(speech['row_endpoint']))['rows']
    row=next(v for v in rows if v['row_idx']==int(speech['row_idx']))
    url=row['row']['audio'][0]['src']
    p.write_bytes(urllib.request.urlopen(url).read())
assert hashlib.sha256(p.read_bytes()).hexdigest()==speech['sha256']
source=json.loads(Path('docs/任务卡/202-证据/continuous-sources.json').read_text())[1]
x=r.load({'path':source['path']})
fan=r.load(next(v for v in m if v['category']=='fan'))
rustle=r.load(next(v for v in m if v['category']=='bed_rustle'))
voice=r.load(speech)
model=sherpa_onnx.AudioTagging(sherpa_onnx.AudioTaggingConfig(model=sherpa_onnx.AudioTaggingModelConfig(zipformer=sherpa_onnx.OfflineZipformerAudioTaggingModelConfig(model=str(r.ROOT/'model/model.int8.onnx')),num_threads=2,provider='cpu'),labels=str(r.ROOT/'model/class_labels_indices.csv'),top_k=527))
rate=16000
# 前后鼾声是同一来源不同30秒片段；喘气用带通形状的噪声包络模拟，不冒充真实患者。
rng=np.random.default_rng(203);gasp=rng.normal(size=rate)*np.sin(np.linspace(0,np.pi,rate))
a=r.norm(r.room(x[:30*rate]),-32);b=r.norm(r.room(x[30*rate:60*rate]),-32)
cases={'simulated_gasp':np.concatenate([a,np.zeros(15*rate),r.norm(gasp,-28),b]),
       'normal_pause':np.concatenate([a,np.zeros(4*rate),b]),
       'rustle_after_pause':np.concatenate([a,np.zeros(15*rate),r.norm(rustle[:2*rate],-28),b]),
       'speech_after_pause':np.concatenate([a,np.zeros(15*rate),r.norm(voice[:2*rate],-28),b]),
       'continuous_snore':r.norm(r.room(x[:120*rate]),-32)}
cases["simulated_gasp_stationary"]=cases["simulated_gasp"].copy()
rows=[];cases_info=[]
for name,signal in cases.items():
    noise=r.norm(rng.normal(size=len(signal)) if name=="simulated_gasp_stationary" else np.resize(fan,len(signal)),-50);signal=signal+noise;env=[];history=[-50]*300
    for off in range(0,len(signal)-31999,32000):
        w=signal[off:off+32000];bg=int(np.median(history));rms=[r.rms(w[i:i+8000]) for i in range(0,32000,8000)];env=(env+rms)[-60:]
        z=np.array(env);mean=z.mean();cv=z.std()/(mean+1e-12);c=z-mean;cor=0.
        if len(z)>=12:
            for lag in range(4,min(12,len(z)//2)+1):
                den=np.linalg.norm(c[:-lag])*np.linalg.norm(c[lag:]);cor=max(cor,float(c[:-lag]@c[lag:])/den if den>1e-15 else 0)
        stream=model.create_stream();stream.accept_waveform(rate,w.astype(np.float32));scores={v.name:float(v.prob) for v in model.compute(stream,527)}
        rows.append(dict(case=name,at=off//16,snore=scores['Snoring'],rhythm=cor,modulation=cv,above=int(np.floor(r.db(w)+.5))-bg,levels=';'.join(str(int(np.clip(np.floor(20*np.log10(max(v,1e-6))+.5),-120,0))-bg) for v in rms)))
        history=(history+[int(np.floor(r.db(w)+.5))])[-300:]
    cases_info.append({'case':name,'seconds':len(signal)/rate,'simulated':True});print(name,flush=True)
with (OUT/'break-windows.csv').open('w') as f:
    out=csv.DictWriter(f,rows[0],lineterminator="\n");out.writeheader();out.writerows(rows)
(OUT/'break-sources.json').write_text(json.dumps({'snore':source,'speech':speech,'background':[v for v in m if v['category'] in {'fan','bed_rustle'}],'cases':cases_info,'gasp':'seed 203 Gaussian noise with sine envelope, simulation only','limits':'No clinical annotations; no tuning on these cases; counts generated by production Kotlin.'},ensure_ascii=False,indent=2))
