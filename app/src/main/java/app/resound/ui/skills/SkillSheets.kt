/** 一张技能卡的详情：内容积木 + 重新生成 / 删除 */
@Composable
fun SkillCardSheet(card: SkillCard, repo: SkillRepository, onDismiss: () -> Unit) {
    val c = Rs.colors
    val scope = rememberCoroutineScope()
    var confirmDelete by remember { mutableStateOf(false) }
    var asked by remember { mutableStateOf(false) }
    var note by remember { mutableStateOf<String?>(null) }
    val skillExists = repo.skills.collectAsState().value.any { it.id == card.skillId }
    RsSheet(card.title, "${card.skillName} · ${cardTime(card)}", onDismiss = onDismiss) {
        if (card.summary.isNotBlank()) {
            Text(card.summary, style = RsType.body, color = c.text,
                modifier = Modifier.fillMaxWidth().clip(RoundedCornerShape(14.dp)).background(skillInk(card.icon).copy(alpha = 0.08f)).padding(14.dp))
        }
        SkillCardBody(card)
        Spacer(Modifier.height(4.dp))
        // 后台生成：离开这里也不会中断，好了会发通知
        val key = card.skillId to card.date
        val gen = key in repo.generating.collectAsState().value
        val done = repo.generated.collectAsState().value[key]
        if (asked && !gen && done != null) note = when (done) {
            is SkillRunResult.Cards -> "已更新"
            is SkillRunResult.Nothing -> "没出新卡：${done.reason}"
            is SkillRunResult.Failed -> done.reason
        }
        note?.let { Text(it, style = RsType.subhead, color = c.textSecondary) }
        if (skillExists) ActionButton(if (gen) "后台生成中…好了会通知你" else "重新生成", ActionKind.Secondary, enabled = !gen) {
            asked = true; note = null
            repo.generate(card.skillId, card.date)
        }
        ActionButton(if (confirmDelete) "确定删除？以后不会再自动出这张卡" else "删除这张卡", ActionKind.Danger) {
            if (!confirmDelete) confirmDelete = true else { repo.deleteCard(card.id); onDismiss() }
        }
    }
}

/** 给某天手动生成：选一个技能，跑完显示结果 */
@Composable
fun MakeCardSheet(date: LocalDate, repo: SkillRepository, onDismiss: () -> Unit) {
    val c = Rs.colors
    val scope = rememberCoroutineScope()
    val skills = repo.skills.collectAsState().value.filter { it.origin != SkillOrigin.Core }
    val generating by repo.generating.collectAsState()
    val generated by repo.generated.collectAsState()
    // 这次打开面板后点过的技能，才显示它的结果
    var asked by remember { mutableStateOf(emptySet<String>()) }
    val label = if (date == LocalDate.now()) "今天" else date.format(DateTimeFormatter.ofPattern("M月d日"))
    RsSheet("给$label 生成卡片", "选一个技能，用这天的记录在后台生成，好了会发通知；已有的同一张会更新。关着的技能也能手动生成。", onDismiss = onDismiss) {
        skills.forEach { s ->
            val busy = (s.id to date) in generating
            val outcome = generated[s.id to date]?.takeIf { s.id in asked && !busy }?.let { r ->
                when (r) {
                    is SkillRunResult.Cards -> "出了 ${r.cards.size} 张，已放进这天"
                    is SkillRunResult.Nothing -> "没出卡：${r.reason}"
                    is SkillRunResult.Failed -> r.reason
                }
            }
            Row(Modifier.fillMaxWidth().clip(RoundedCornerShape(16.dp)).background(c.background)
                .springClick {
                    if (busy) return@springClick
                    asked = asked + s.id
                    repo.generate(s.id, date)
                }.padding(12.dp), verticalAlignment = Alignment.CenterVertically) {
                SkillIcon(s.icon, 38.dp)
                Spacer(Modifier.width(12.dp))
                Column(Modifier.weight(1f)) {
                    Text(s.name, style = RsType.body.copy(fontWeight = FontWeight.SemiBold), color = c.text)
                    val sub = when {
                        busy -> "后台生成中…可以先去做别的，好了会通知你"
                        outcome != null -> outcome
                        else -> s.summary
                    }
                    Text(sub, style = RsType.caption, color = if (busy || outcome != null) skillInk(s.icon) else c.textSecondary, maxLines = 2)
                }
            }
        }
    }
}
